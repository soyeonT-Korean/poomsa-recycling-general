/* 받침 유무에 따라 조사 자동 선택 (예: josa('밥','은','는')='은', josa('강아지','은','는')='는') */
function josa(word,on,no){
  if(!word) return on;
  const code=word.charCodeAt(word.length-1);
  if(code<0xAC00||code>0xD7A3) return on;      // 한글 음절이 아니면 기본값
  return ((code-0xAC00)%28!==0) ? on : no;     // 종성(받침)이 있으면 on
}

